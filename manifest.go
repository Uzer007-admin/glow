package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
)

type manifestFunction struct {
	Name       string              `json:"name"`
	GoName     string              `json:"go_name"`
	Required   bool                `json:"required"`
	Return     manifestType        `json:"return"`
	Parameters []manifestParameter `json:"parameters"`
}

type manifestType struct {
	C  string `json:"c"`
	Go string `json:"go"`
}

type manifestParameter struct {
	Name string       `json:"name"`
	Type manifestType `json:"type"`
}

func describeType(typ Type) manifestType {
	goType := typ.GoType()
	if typ.IsVoid() {
		goType = ""
	}
	return manifestType{C: typ.CType(), Go: goType}
}

func (pkg *Package) writeManifest(dir string) error {
	manifest := struct {
		Schema          int                `json:"schema"`
		API             string             `json:"api"`
		Version         string             `json:"version"`
		Profile         string             `json:"profile"`
		ContextDispatch bool               `json:"context_dispatch,omitempty"`
		Functions       []manifestFunction `json:"functions"`
		Enums           []string           `json:"enums"`
	}{Schema: 2, API: pkg.API, Version: pkg.Version.String(), Profile: pkg.Profile, ContextDispatch: pkg.ContextDispatch,
		Functions: make([]manifestFunction, 0, len(pkg.Functions)), Enums: make([]string, 0, len(pkg.Enums))}
	for name, fn := range pkg.Functions {
		function := manifestFunction{Name: name, GoName: fn.GoName, Required: fn.Required,
			Return: describeType(fn.Return), Parameters: make([]manifestParameter, 0, len(fn.Parameters))}
		for _, parameter := range fn.Parameters {
			function.Parameters = append(function.Parameters, manifestParameter{parameter.Name, describeType(parameter.Type)})
		}
		manifest.Functions = append(manifest.Functions, function)
	}
	sort.Slice(manifest.Functions, func(i, j int) bool { return manifest.Functions[i].Name < manifest.Functions[j].Name })
	for name := range pkg.Enums {
		manifest.Enums = append(manifest.Enums, name)
	}
	sort.Strings(manifest.Enums)
	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "symbol_manifest.json"), append(data, '\n'), 0644)
}

// Publish only the generated files. Parse/format failures leave the previous
// output intact; publication errors restore files already replaced in this run.
// This is a rollback guarantee, not a multi-file filesystem transaction.
func publishGenerated(dir, staging string, files []string, removeDebug bool) error {
	type backup struct {
		name   string
		data   []byte
		mode   os.FileMode
		exists bool
		remove bool
		skip   bool
	}
	var backups []backup
	names := append([]string(nil), files...)
	if removeDebug {
		names = append(names, "debug.go")
	}
	// Check every destination before the first publication, including symlinks.
	for _, name := range names {
		old := backup{name: name, remove: removeDebug && name == "debug.go"}
		info, err := os.Lstat(filepath.Join(dir, name))
		if errors.Is(err, os.ErrNotExist) {
			if !old.remove {
				backups = append(backups, old)
			}
			continue
		}
		if err != nil {
			return err
		}
		if !info.Mode().IsRegular() {
			return fmt.Errorf("generated destination is not a regular file: %s", name)
		}
		old.data, err = os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return err
		}
		if old.remove && !bytes.HasPrefix(bytes.TrimSpace(old.data), []byte("// Code generated by glow")) {
			return fmt.Errorf("refuse to remove non-generated %s", name)
		}
		old.exists, old.mode = true, info.Mode().Perm()
		if !old.remove {
			generated, err := os.ReadFile(filepath.Join(staging, name))
			if err != nil {
				return err
			}
			old.skip = bytes.Equal(old.data, generated)
		}
		backups = append(backups, old)
	}
	for i, old := range backups {
		if old.skip {
			continue
		}
		path := filepath.Join(dir, old.name)
		var err error
		if old.remove {
			err = os.Remove(path)
		} else {
			err = os.Rename(filepath.Join(staging, old.name), path)
		}
		if err == nil {
			continue
		}
		failure := fmt.Errorf("publish %s: %w", old.name, err)
		for n := i - 1; n >= 0; n-- {
			previous := backups[n]
			if previous.skip {
				continue
			}
			path := filepath.Join(dir, previous.name)
			if previous.exists {
				err = os.WriteFile(path, previous.data, previous.mode)
			} else {
				err = os.Remove(path)
			}
			if err != nil {
				failure = errors.Join(failure, fmt.Errorf("restore %s: %w", previous.name, err))
			}
		}
		return failure
	}
	return nil
}
