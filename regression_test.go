func TestRestrictionValidation(t *testing.T) {
	for _, content := range []string{
		`{"functions":["glTypo"]}`,
		`{"enums":["GL_TYPO"]}`,
		`{"functions":["glClear","glClear"]}`,
		`{"function":["glClear"]}`,
		`{"functions":["glClear"]} {}`,
		`null`,
	} {
		pkg := &Package{Enums: map[string]*Enum{"GL_TRUE": {}}, Functions: map[string]*PackageFunction{"glClear": {}}}
		path := filepath.Join(t.TempDir(), "restriction.json")
		if err := os.WriteFile(path, []byte(content), 0644); err != nil {
			t.Fatal(err)
		}
		if err := performRestriction(pkg, path); err == nil {
			t.Fatalf("invalid restriction accepted: %s", content)
		}
		if len(pkg.Enums) != 1 || len(pkg.Functions) != 1 {
			t.Fatalf("invalid restriction mutated package: %s", content)
		}
	}
}

func TestRestrictionEmptyAndOmittedLists(t *testing.T) {
	pkg := &Package{Enums: map[string]*Enum{"GL_TRUE": {}}, Functions: map[string]*PackageFunction{"glClear": {}}}
	path := filepath.Join(t.TempDir(), "restriction.json")
	if err := os.WriteFile(path, []byte(`{"functions":[]}`), 0644); err != nil {
		t.Fatal(err)
	}
	if err := performRestriction(pkg, path); err != nil {
		t.Fatal(err)
	}
	if len(pkg.Enums) != 1 || len(pkg.Functions) != 0 {
		t.Fatalf("omitted enums must remain; explicit empty functions must be removed: %+v", pkg)
	}
}
