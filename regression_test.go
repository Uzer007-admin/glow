func TestGenerationFailurePreservesPreviousOutput(t *testing.T) {
	root := t.TempDir()
	templates := filepath.Join(root, "templates")
	os.Mkdir(templates, 0755)
	for _, name := range []string{"package", "conversions", "procaddr"} {
		os.WriteFile(filepath.Join(templates, name+".tmpl"), []byte("package broken\nfunc {"), 0644)
	}
	out := filepath.Join(root, "out")
	os.Mkdir(out, 0755)
	old := []byte("package gl\n// previous working bindings\n")
	os.WriteFile(filepath.Join(out, "package.go"), old, 0644)
	pkg := &Package{Name: "gl", TmplDir: templates}
	if err := pkg.GeneratePackage(out); err == nil {
		t.Fatal("invalid generated Go accepted")
	}
	actual, err := os.ReadFile(filepath.Join(out, "package.go"))
	if err != nil || string(actual) != string(old) {
		t.Fatalf("previous output changed: %q; %v", actual, err)
	}
	staging, _ := filepath.Glob(filepath.Join(out, ".glow-generation-*"))
	if len(staging) != 0 {
		t.Fatal("generation staging directories remain")
	}
}

func TestRestrictedRegenerationRemovesOnlyGeneratedDebug(t *testing.T) {
	root := t.TempDir()
	templates := filepath.Join(root, "templates")
	os.Mkdir(templates, 0755)
	for _, name := range []string{"package", "conversions", "procaddr"} {
		os.WriteFile(filepath.Join(templates, name+".tmpl"), []byte("package gl\n"), 0644)
	}
	out := filepath.Join(root, "out")
	os.Mkdir(out, 0755)
	os.WriteFile(filepath.Join(out, "debug.go"), []byte("// Code generated by glow\npackage gl\n"), 0644)
	// Generator formatting must not touch caller-owned files in its output directory.
	custom := []byte("package custom\nnot valid Go syntax\n")
	os.WriteFile(filepath.Join(out, "custom.go"), custom, 0644)
	pkg := &Package{Name: "gl", TmplDir: templates}
	if err := pkg.GeneratePackage(out); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(out, "debug.go")); !os.IsNotExist(err) {
		t.Fatal("stale generated debug file remains")
	}
	actual, _ := os.ReadFile(filepath.Join(out, "custom.go"))
	if string(actual) != string(custom) {
		t.Fatal("caller-owned file changed")
	}
	os.WriteFile(filepath.Join(out, "debug.go"), []byte("package gl\n// caller-owned debug code\n"), 0644)
	if err := pkg.GeneratePackage(out); err == nil || !strings.Contains(err.Error(), "non-generated") {
		t.Fatalf("non-generated debug deletion accepted: %v", err)
	}
	// A string mentioning Glow inside caller-owned code is not a generated header.
	os.WriteFile(filepath.Join(out, "debug.go"), []byte("package gl\nconst source = \"Code generated by glow\"\n"), 0644)
	if err := pkg.GeneratePackage(out); err == nil || !strings.Contains(err.Error(), "non-generated") {
		t.Fatalf("marker inside caller-owned code accepted: %v", err)
	}
}

