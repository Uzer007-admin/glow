func TestStructSignature(t *testing.T) {
	_, typ, err := parseSignature(xmlSignature(`struct <ptype>AHardwareBuffer</ptype> *<name>buffer</name>`))
	if err != nil || typ.Name != "struct AHardwareBuffer" || typ.GoCType() != "*C.struct_AHardwareBuffer" {
		t.Fatalf("%+v %v", typ, err)
	}
}

func TestStructTypedefLookup(t *testing.T) {
	for _, name := range []string{"struct _cl_context", "AHardwareBuffer"} {
		definition := &Typedef{Name: name}
		types := specTypedefs{specRef{name, ""}: &specTypedef{typedef: definition, ordinal: 0}}
		selected := make([]*Typedef, 1)
		request := name
		if name == "AHardwareBuffer" {
			request = "struct " + name
		}
		types.selectRequired(request, "gl", selected)
		if selected[0] != definition {
			t.Fatalf("missing %s", name)
		}
	}
}

